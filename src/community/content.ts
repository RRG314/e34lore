export type Editorial = {
  slug: string;
  category: string;
  title: string;
  summary: string;
  paragraphs: string[];
  prompts: string[];
  sources: string[];
  kind: "resource" | "known-issue" | "manual-clarification";
  template: TemplateId;
};
function entry(
  category: string,
  slug: string,
  title: string,
  summary: string,
  body: string,
  prompts: string[],
  sources: string[] = [],
  kind: Editorial["kind"] = "resource",
): Editorial {
  const c = communityCategories.find((c) => c.id === category)!;
  return {
    slug,
    category: c.name,
    title,
    summary,
    paragraphs: body.split("\n\n"),
    prompts,
    sources,
    kind,
    template: c.template,
  };
}
